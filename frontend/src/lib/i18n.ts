const dicts: Record<Lang, Record<string, string>> = { en, fa };

/** Translate a key, optionally interpolating `{param}` placeholders. */
export function t(key: string, params?: Record<string, string | number>): string {
  let s = dicts[i18nState.lang][key] ?? dicts.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

/** Switch language and mirror the document direction. */
export function setLang(lang: Lang): void {
  i18nState.lang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "fa" ? "rtl" : "ltr";
}
