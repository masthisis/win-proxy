package reporting

// markdown.go — renders a Capture as the GitHub issue body (#36).
//
// Layout goals (so an AI or human can triage without the user's machine):
//   1. headline table (versions, OS, uptime, core, engine state)
//   2. full detail + labeled extras
//   3. redacted settings snapshot (JSON)
//   4. log tail (code fence)
//   5. goroutine dump (code fence) for the crash-class reports
//
// Four-backtick fences are used so log lines containing triple backticks
// cannot break out. splitMarkdown caps each part under GitHub's 65,536-char
// limit, cutting at line boundaries; overflow becomes issue comments.

import (
	"encoding/json"
	"fmt"
	"strings"
	"time"
)

const fence = "````"

// renderMarkdown renders the full issue body for a capture.
func renderMarkdown(c *Capture) string {
	var b strings.Builder
	fmt.Fprintf(&b, "## %s report\n\n", c.Type)
	fmt.Fprintf(&b, "**%s**\n\n", c.Detail)
	fmt.Fprintf(&b, "Auto-generated by NeuroRift %s · signature `%s` · captured %s · local bundle `reports/pending/%s.json`\n\n",
		c.Version, c.Signature, c.Time.UTC().Format(time.RFC3339), c.ID)

	b.WriteString("| field | value |\n| --- | --- |\n")
	row := func(k, v string) {
		if v != "" {
			v = strings.ReplaceAll(v, "|", "\\|")
			v = strings.ReplaceAll(v, "\n", " ")
			fmt.Fprintf(&b, "| %s | %s |\n", k, v)
		}
	}
	row("app version", c.Version)
	row("os/arch", c.OS)
	row("go version", c.GoVersion)
	row("uptime", (time.Duration(c.UptimeSec) * time.Second).String())
	row("core (mihomo)", c.CoreVersion)
	row("engine state", c.EngineState)
	row("report type", string(c.Type))
	b.WriteString("\n")

	if c.Details != "" && c.Details != c.Detail {
		fmt.Fprintf(&b, "### Detail\n\n%s\n\n", c.Details)
	}
	if len(c.Extras) > 0 {
		b.WriteString("### Context\n\n")
		keys := make([]string, 0, len(c.Extras))
		for k := range c.Extras {
			keys = append(keys, k)
		}
		sortStrings(keys)
		for _, k := range keys {
			fmt.Fprintf(&b, "**%s**\n\n%s\n\n", k, c.Extras[k])
		}
	}
	if len(c.Settings) > 0 {
		b.WriteString("### Settings (redacted)\n\n")
		b.WriteString(fence + "json\n")
		b.WriteString(indentJSON(c.Settings))
		b.WriteString("\n" + fence + "\n\n")
	}
	if len(c.LogTail) > 0 {
		b.WriteString("### App log tail\n\n" + fence + "\n")
		for _, l := range c.LogTail {
			b.WriteString(l)
			b.WriteByte('\n')
		}
		b.WriteString(fence + "\n\n")
	}
	if c.Goroutines != "" {
		b.WriteString("### Goroutine dump\n\n" + fence + "\n")
		b.WriteString(c.Goroutines)
		if !strings.HasSuffix(c.Goroutines, "\n") {
			b.WriteByte('\n')
		}
		b.WriteString(fence + "\n\n")
	}
	return b.String()
}

// splitMarkdown cuts body into at most 1+maxComments parts of <=limit chars,
// slicing at line boundaries and marking continuations.
func splitMarkdown(body string, limit int, maxComments int) []string {
	if len(body) <= limit {
		return []string{body}
	}
	var parts []string
	rest := body
	for len(rest) > 0 && len(parts) < maxComments+1 {
		if len(rest) <= limit {
			parts = append(parts, rest)
			break
		}
		cut := limit
		if i := strings.LastIndexByte(rest[:limit], '\n'); i > limit/2 {
			cut = i + 1
		}
		parts = append(parts, rest[:cut])
		rest = rest[cut:]
	}
	if len(rest) > 0 {
		// Anything beyond the comment budget stays in the local bundle file;
		// note the truncation explicitly so the triage knows.
		note := fmt.Sprintf("\n\n---\n_[report truncated after %d parts — the full bundle is stored locally in %%APPDATA%%\\NeuroRift\\reports\\]_\n", len(parts))
		parts[len(parts)-1] += note
	}
	for i := range parts {
		if i == 0 {
			continue
		}
		parts[i] = fmt.Sprintf("**continuation %d/%d**\n\n", i, len(parts)-1) + parts[i]
	}
	return parts
}

func sortStrings(s []string) {
	for i := 1; i < len(s); i++ {
		for j := i; j > 0 && s[j] < s[j-1]; j-- {
			s[j], s[j-1] = s[j-1], s[j]
		}
	}
}

// indentJSON serializes v as indented JSON (fallback: empty object).
func indentJSON(v any) string {
	data, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return "{}"
	}
	return string(data)
}
